const ApiResponse = require('../utils/response');
const logger = require('../utils/logger');
const fieldMappingService = require('../services/fieldMapping.service');
const userAutoCreationService = require('../services/userAutoCreation.service');

/**
 * Controlador para administrar mapeos de usuarios y auto-creación
 */
class UserMappingController {
    /**
     * Obtener reporte de usuarios auto-generados
     */
    getAutoGeneratedUsers = async (req, res) => {
        try {
            const { sourceAreaId } = req.query;

            const users = await userAutoCreationService.getAutoGeneratedUsersReport(sourceAreaId);

            return ApiResponse.success(res, {
                users,
                total: users.length,
                summary: this.generateUsersSummary(users)
            }, 'Reporte de usuarios auto-generados obtenido exitosamente');

        } catch (error) {
            logger.error('Error obteniendo usuarios auto-generados:', error);
            return ApiResponse.error(res, error.message, 500);
        }
    };

    /**
     * Obtener mapeos de campo por área
     */
    getFieldMappings = async (req, res) => {
        try {
            const { areaId } = req.params;

            const mappings = await fieldMappingService.getFieldMappings(areaId);

            // Filtrar solo los mapeos relacionados con usuarios
            const userMappings = mappings.filter(mapping =>
                mapping.transformation &&
                (mapping.transformation.includes('USER_LOOKUP') ||
                 mapping.targetField.includes('Id') &&
                 ['salesManagerId', 'salesExecutiveId', 'salesLeaderId', 'architectId', 'designManagerId', 'designCoordinatorId'].includes(mapping.targetField))
            );

            return ApiResponse.success(res, {
                mappings: userMappings,
                total: userMappings.length,
                availableContexts: this.getAvailableContexts()
            }, 'Mapeos de usuario obtenidos exitosamente');

        } catch (error) {
            logger.error('Error obteniendo mapeos de campo:', error);
            return ApiResponse.error(res, error.message, 500);
        }
    };

    /**
     * Crear nuevo mapeo de usuario
     */
    createUserMapping = async (req, res) => {
        try {
            const { areaId } = req.params;
            const { sourceField, targetField, context, isRequired, description } = req.body;

            // Validar datos requeridos
            if (!sourceField || !targetField || !context) {
                return ApiResponse.error(res, 'sourceField, targetField y context son requeridos', 400);
            }

            // Validar que el contexto sea válido
            const availableContexts = this.getAvailableContexts();
            if (!availableContexts.find(c => c.key === context)) {
                return ApiResponse.error(res, `Contexto inválido. Contextos disponibles: ${availableContexts.map(c => c.key).join(', ')}`, 400);
            }

            const mappingData = {
                sourceAreaId: areaId,
                sourceField,
                targetField,
                targetTable: 'staging_projects',
                transformation: `USER_LOOKUP_OR_CREATE:${context}`,
                isRequired: isRequired || false,
                description: description || `Auto-crea usuarios con contexto ${context}`,
                orderIndex: 0,
                isActive: true
            };

            const mapping = await fieldMappingService.createFieldMapping(mappingData);

            return ApiResponse.success(res, mapping, 'Mapeo de usuario creado exitosamente');

        } catch (error) {
            logger.error('Error creando mapeo de usuario:', error);
            return ApiResponse.error(res, error.message, 500);
        }
    };

    /**
     * Actualizar mapeo de usuario
     */
    updateUserMapping = async (req, res) => {
        try {
            const { mappingId } = req.params;
            const { sourceField, targetField, context, isRequired, description, isActive } = req.body;

            const updateData = {};

            if (sourceField) updateData.sourceField = sourceField;
            if (targetField) updateData.targetField = targetField;
            if (context) {
                // Validar contexto
                const availableContexts = this.getAvailableContexts();
                if (!availableContexts.find(c => c.key === context)) {
                    return ApiResponse.error(res, `Contexto inválido. Contextos disponibles: ${availableContexts.map(c => c.key).join(', ')}`, 400);
                }
                updateData.transformation = `USER_LOOKUP_OR_CREATE:${context}`;
            }
            if (typeof isRequired === 'boolean') updateData.isRequired = isRequired;
            if (description) updateData.description = description;
            if (typeof isActive === 'boolean') updateData.isActive = isActive;

            const mapping = await fieldMappingService.updateFieldMapping(mappingId, updateData);

            return ApiResponse.success(res, mapping, 'Mapeo de usuario actualizado exitosamente');

        } catch (error) {
            logger.error('Error actualizando mapeo de usuario:', error);
            return ApiResponse.error(res, error.message, 500);
        }
    };

    /**
     * Obtener contextos disponibles para usuarios
     */
    getAvailableContexts = () => {
        return [
            {
                key: 'sales_manager',
                name: 'Gerente de Ventas',
                role: 'COORDINADOR',
                emailPrefix: 'ventas',
                description: 'Gerentes y directores de ventas'
            },
            {
                key: 'sales_executive',
                name: 'Ejecutivo de Ventas',
                role: 'COLABORADOR',
                emailPrefix: 'ventas',
                description: 'Ejecutivos y representantes de ventas'
            },
            {
                key: 'sales_leader',
                name: 'Líder de Ventas',
                role: 'COORDINADOR',
                emailPrefix: 'ventas',
                description: 'Líderes de equipo de ventas'
            },
            {
                key: 'architect',
                name: 'Arquitecto',
                role: 'COLABORADOR',
                emailPrefix: 'arquitectura',
                description: 'Arquitectos de soluciones'
            },
            {
                key: 'design_manager',
                name: 'Gerente de Diseño',
                role: 'COORDINADOR',
                emailPrefix: 'diseno',
                description: 'Gerentes de área de diseño'
            },
            {
                key: 'design_coordinator',
                name: 'Coordinador de Diseño',
                role: 'COORDINADOR',
                emailPrefix: 'diseno',
                description: 'Coordinadores de proyectos de diseño'
            },
            {
                key: 'default',
                name: 'Usuario Genérico',
                role: 'COLABORADOR',
                emailPrefix: 'usuario',
                description: 'Usuario sin rol específico'
            }
        ];
    };

    /**
     * Generar resumen de usuarios auto-generados
     */
    generateUsersSummary = (users) => {
        const summary = {
            totalUsers: users.length,
            byContext: {},
            byRole: {},
            byArea: {},
            recentlyCreated: users.filter(u => {
                const daysSinceCreation = (new Date() - new Date(u.createdAt)) / (1000 * 60 * 60 * 24);
                return daysSinceCreation <= 7;
            }).length
        };

        users.forEach(user => {
            // Por contexto
            const context = user.context || 'unknown';
            summary.byContext[context] = (summary.byContext[context] || 0) + 1;

            // Por rol
            summary.byRole[user.role] = (summary.byRole[user.role] || 0) + 1;

            // Por área
            const areaName = user.area?.name || 'Sin área';
            summary.byArea[areaName] = (summary.byArea[areaName] || 0) + 1;
        });

        return summary;
    };

    /**
     * Configuración rápida para área común
     */
    setupCommonMappings = async (req, res) => {
        try {
            const { areaId } = req.params;

            const commonMappings = [
                {
                    sourceField: 'Gerente de Ventas',
                    targetField: 'salesManagerId',
                    context: 'sales_manager',
                    description: 'Auto-crea gerentes de venta'
                },
                {
                    sourceField: 'Ejecutivo Venta',
                    targetField: 'salesExecutiveId',
                    context: 'sales_executive',
                    description: 'Auto-crea ejecutivos de venta'
                },
                {
                    sourceField: 'Líder de Ventas',
                    targetField: 'salesLeaderId',
                    context: 'sales_leader',
                    description: 'Auto-crea líderes de venta'
                },
                {
                    sourceField: 'Arquitecto',
                    targetField: 'architectId',
                    context: 'architect',
                    description: 'Auto-crea arquitectos'
                },
                {
                    sourceField: 'Coordinador de Diseño',
                    targetField: 'designCoordinatorId',
                    context: 'design_coordinator',
                    description: 'Auto-crea coordinadores de diseño'
                },
                {
                    sourceField: 'Gerente de Diseño',
                    targetField: 'designManagerId',
                    context: 'design_manager',
                    description: 'Auto-crea gerentes de diseño'
                }
            ];

            const createdMappings = [];

            for (const mapping of commonMappings) {
                const mappingData = {
                    sourceAreaId: areaId,
                    sourceField: mapping.sourceField,
                    targetField: mapping.targetField,
                    targetTable: 'staging_projects',
                    transformation: `USER_LOOKUP_OR_CREATE:${mapping.context}`,
                    isRequired: false,
                    description: mapping.description,
                    orderIndex: 0,
                    isActive: true
                };

                try {
                    const created = await fieldMappingService.createFieldMapping(mappingData);
                    createdMappings.push(created);
                } catch (error) {
                    logger.warn(`Mapeo ya existe o error: ${mapping.sourceField}`, error.message);
                }
            }

            return ApiResponse.success(res, {
                created: createdMappings,
                total: createdMappings.length
            }, `Configuración común creada: ${createdMappings.length} mapeos`);

        } catch (error) {
            logger.error('Error configurando mapeos comunes:', error);
            return ApiResponse.error(res, error.message, 500);
        }
    };
}

module.exports = new UserMappingController();